import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=path.join(root,'public/assets/equipment/modules');
const out=path.join(root,'src/shared/data/equipment-fit-modules.generated.ts');
const editorOut=path.join(root,'src/shared/data/editor-equipment.generated.ts');
fs.mkdirSync(dir,{recursive:true});
const rows=fs.readdirSync(dir,{withFileTypes:true}).filter(x=>x.isFile()&&/\.glb$/i.test(x.name)).map(x=>x.name).sort().map(name=>{
  const id=name.replace(/\.glb$/i,'');
  if(!/^[a-z0-9][a-z0-9-]*$/i.test(id))throw new Error(`Invalid equipment module filename: ${name}. Use <item-id>.glb`);
  return [id,`/assets/equipment/modules/${name}`];
});
const body='/** AUTO-GENERATED by scripts/sync-equipment-fit-modules.mjs. Do not hand edit. */\n'+
  `export const EQUIPMENT_FIT_MODULES:Readonly<Record<string,string>>=${JSON.stringify(Object.fromEntries(rows),null,2)};\n`;
fs.writeFileSync(out,body);
const registryFile=path.join(dir,'editor-equipment-registry.json');let registry={fitVersion:'HF9',items:{},appearances:{}};
if(fs.existsSync(registryFile)){registry=JSON.parse(fs.readFileSync(registryFile,'utf8'));if(registry.fitVersion!=='HF9'||!registry.items||!registry.appearances)throw new Error('Invalid HF9 editor equipment registry.');}
const editorBody='/** AUTO-GENERATED by the HF9 local editor import pipeline. Do not hand edit. */\n'+
  "import type {Appearance,ItemBase} from '../types';\n"+
  `export const EDITOR_IMPORTED_ITEMS:Readonly<Record<string,ItemBase>>=${JSON.stringify(registry.items,null,2)};\n`+
  `export const EDITOR_IMPORTED_APPEARANCES:Readonly<Record<string,Appearance>>=${JSON.stringify(registry.appearances,null,2)};\n`;
fs.writeFileSync(editorOut,editorBody);
console.log(`HF9 EQUIPMENT MODULE SYNC: ${rows.length} GLB module(s), ${Object.keys(registry.items).length} editor item(s)`);
